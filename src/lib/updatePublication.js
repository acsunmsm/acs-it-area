import { supabase } from './supabaseClient';

// Match the original cover so a stale editor cannot restore a removed file.
export async function updatePublication(table, id, originalImage, changes) {
  let query = supabase.from(table).update(changes).eq('id', id);
  query = originalImage != null ? query.eq('imagen_url', originalImage) : query.is('imagen_url', null);
  const { error } = await query.select('id').single();
  if (error) {
    if (changes.imagen_url !== originalImage && error.code) await removePublicationCover(changes.imagen_url);
    throw error;
  }
  if (originalImage !== changes.imagen_url) await removePublicationCover(originalImage);
}

export async function removePublicationCover(originalImage) {
  if (!originalImage) return;

  // Only covers generated by these editors belong to this cleanup.
  const base = process.env.NEXT_PUBLIC_SUPABASE_URL + '/storage/v1/object/public/';
  if (!originalImage.startsWith(base)) return;
  const match = /^(eventos|noticias)\/((?:noticias\/)?flyers\/[0-9]+-[a-z0-9]+\.[a-z0-9]+)$/i.exec(originalImage.slice(base.length));
  if (!match) return;
  try {
    const references = await Promise.all(['eventos', 'noticias'].map(table =>
      supabase.from(table).select('id', { count: 'exact', head: true }).eq('imagen_url', originalImage)
    ));
    if (references.some(result => result.error || result.count !== 0)) return;
    const { error: cleanupError } = await supabase.storage.from(match[1]).remove([match[2]]);
    if (cleanupError) console.warn('No se pudo retirar la portada anterior:', cleanupError.message);
  } catch (err) {
    console.warn('No se pudo retirar la portada anterior:', err);
  }
}
